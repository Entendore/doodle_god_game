class CombinationEngine:
    """
    Multi-index combination resolution system.

    Data structures:
      _forward:  dict[(a,b)] -> result   O(1) exact lookup (normalized a<=b)
      _adj:      dict[elem] -> dict[partner] -> result   O(1) per partner
      _reverse:  dict[result] -> list[(a,b)]   recipe lookup
      _cat_idx:  dict[(cat_a,cat_b)] -> list[(a,b,result)]   category filter
      _partners: dict[elem] -> set[partner]   quick "can combine?" check
      _tiers:    dict[elem] -> int   discovery depth from base elements
    """

    def __init__(self):
        self._forward = {}
        self._adj = defaultdict(dict)
        self._reverse = defaultdict(list)
        self._cat_idx = defaultdict(list)
        self._partners = defaultdict(set)
        self._tiers = {}

    @staticmethod
    def _norm(a, b):
        """Normalize combination key so (a,b) always has a<=b."""
        return (a, b) if a <= b else (b, a)

    def add(self, a, b, result):
        """Register a combination. Auto-indexed in all directions."""
        key = self._norm(a, b)
        self._forward[key] = result
        self._adj[a][b] = result
        self._adj[b][a] = result
        self._reverse[result].append((a, b))
        self._partners[a].add(b)
        self._partners[b].add(a)
        cat_a = ELEMENTS[a]["cat"]
        cat_b = ELEMENTS[b]["cat"]
        self._cat_idx[self._norm(cat_a, cat_b)].append((a, b, result))

    def try_combine(self, a, b):
        """Try combining two elements. Returns result or None. O(1)."""
        return self._forward.get(self._norm(a, b))

    def get_partners(self, element):
        """Get all {partner: result} for an element. O(1) access."""
        return dict(self._adj.get(element, {}))

    def has_partners(self, element):
        """Quick check if element has ANY combination. O(1)."""
        return bool(self._partners.get(element))

    def get_recipes(self, result):
        """Get all (a, b) pairs that produce this element."""
        return list(self._reverse.get(result, []))

    def get_by_category(self, cat_a, cat_b):
        """Get all combos between two categories."""
        return self._cat_idx.get(self._norm(cat_a, cat_b), [])

    def compute_tiers(self, base_elements):
        """BFS from base elements to assign discovery tiers."""
        tiers = {e: 0 for e in base_elements}
        frontier = list(base_elements)
        tier = 1
        while frontier:
            next_frontier = []
            for elem in frontier:
                for partner, result in self._adj.get(elem, {}).items():
                    if result not in tiers and partner in tiers:
                        tiers[result] = tier
                        next_frontier.append(result)
            frontier = list(set(next_frontier))
            if not frontier:
                break
            tier += 1
        self._tiers = tiers
        return tiers

    def get_tier(self, element):
        """Get discovery tier of an element."""
        return self._tiers.get(element, -1)

    def get_hint(self, discovered):
        """Find an undiscovered combination using BFS-tier order."""
        best = None
        best_tier = 999
        for (a, b), result in self._forward.items():
            if a in discovered and b in discovered and result not in discovered:
                t = self._tiers.get(result, 999)
                if t < best_tier:
                    best_tier = t
                    best = (a, b, result)
        return best

    def all_combos_for(self, element, discovered):
        """Get all valid undiscovered combos for an element."""
        results = []
        for partner, result in self._adj.get(element, {}).items():
            if partner in discovered and result not in discovered:
                results.append((partner, result))
        return results


class ElementTrie:
    """Trie-based O(m+k) prefix search for element names."""

    def __init__(self, elements):
        self.root = {}
        self.values = []
        for name in elements:
            self.insert(name)

    def insert(self, name):
        node = self.root
        for ch in name.lower():
            if ch not in node:
                node[ch] = {}
            node = node[ch]
        node["__end__"] = len(self.values)
        self.values.append(name)

    def search_prefix(self, prefix):
        """Return all elements starting with prefix. O(m+k)."""
        node = self.root
        for ch in prefix.lower():
            if ch not in node:
                return []
            node = node[ch]
        results = []
        self._collect(node, results)
        return results

    def _collect(self, node, results):
        if "__end__" in node:
            results.append(self.values[node["__end__"]])
        for ch, child in node.items():
            if ch != "__end__":
                self._collect(child, results)


